package com.agy.ru

import android.content.Context
import org.json.JSONArray
import org.json.JSONObject
import java.io.IOException
import java.util.UUID

/** One rendered transcript entry derived from a cortex step. */
class HibouStep(
    val index: Int,
    val type: String,
    val status: String,
    val text: String,
    val thinking: String,
    val tool: String?
)

class HibouConversationSummary(
    val id: String,
    val title: String,
    val stepCount: Int,
    val updatedAt: Long,
    val running: Boolean
)

class HibouModel(
    val id: String,
    val label: String,
    val recommended: Boolean,
    val supportsThinking: Boolean
)

class HibouStreamHandle internal constructor(
    private val thread: Thread,
    internal val connection: HibouConnect
) {
    fun cancel() {
        connection.cancel()
        thread.interrupt()
    }
}

/**
 * Domain layer over [HibouConnect].
 *
 * The call shapes mirror what the web bundle sends, verified against
 * `native-src/proto/descriptors.json`:
 *
 *   StartCascade              {cascadeId, trajectoryType, source, metadata}
 *   SendUserCascadeMessage    {cascadeId, items:[{text}], metadata}
 *   StreamAgentStateUpdates   {conversationId, subscriberId, trajectoryVerbosity}
 *   GetCascadeTrajectory      {cascadeId}
 *   GetAllCascadeTrajectories {}
 *
 * Cascade ids are generated by the client, exactly like the web client does
 * with `crypto.randomUUID()`, so no round-trip is needed to start a chat.
 */
class HibouChatClient(private val ctx: Context) {

    companion object {
        const val VERBOSITY_PROD_UI = "CLIENT_TRAJECTORY_VERBOSITY_PROD_UI"
        const val SOURCE_CASCADE_CLIENT = "CORTEX_TRAJECTORY_SOURCE_CASCADE_CLIENT"
        const val TYPE_USER_MAINLINE = "CORTEX_TRAJECTORY_TYPE_USER_MAINLINE"
    }

    fun isReady(): Boolean = HibouCore.isReady()

    fun newCascadeId(): String = UUID.randomUUID().toString()

    private fun connect(): HibouConnect {
        val activity = HibouCore.currentActivity()
        val base = HibouCore.baseUrl(activity)
            ?: throw IOException("core is not running yet")
        return HibouConnect(base, HibouCore.csrfToken(activity))
    }

    // -- conversation lifecycle -----------------------------------------

    fun startCascade(cascadeId: String, workspaceUris: List<String> = emptyList()) {
        val request = JSONObject()
        request.put("cascadeId", cascadeId)
        request.put("trajectoryType", TYPE_USER_MAINLINE)
        request.put("source", SOURCE_CASCADE_CLIENT)
        request.put("metadata", HibouCore.metadata(ctx))
        if (workspaceUris.isNotEmpty()) {
            request.put("workspaceUris", JSONArray(workspaceUris))
        }
        connect().unary("StartCascade", request)
    }

    fun sendMessage(cascadeId: String, text: String) {
        val item = JSONObject()
        item.put("text", text)
        val items = JSONArray()
        items.put(item)

        val request = JSONObject()
        request.put("cascadeId", cascadeId)
        request.put("items", items)
        request.put("metadata", HibouCore.metadata(ctx))
        connect().unary("SendUserCascadeMessage", request)
    }

    fun cancel(cascadeId: String) {
        val request = JSONObject()
        request.put("cascadeId", cascadeId)
        try {
            connect().unary("CancelCascadeInvocation", request)
        } catch (_: Throwable) {
        }
    }

    fun delete(cascadeId: String) {
        val request = JSONObject()
        request.put("cascadeId", cascadeId)
        connect().unary("DeleteCascadeTrajectory", request)
    }

    /**
     * Opens `StreamAgentStateUpdates`.  [onUpdate] receives each
     * `AgentStateUpdate` object; [onDone] receives null on a clean end or the
     * failure.  Both run on the stream thread.
     */
    fun streamUpdates(
        cascadeId: String,
        onUpdate: (JSONObject) -> Unit,
        onDone: (Throwable?) -> Unit
    ): HibouStreamHandle {
        val connection = connect()
        val request = JSONObject()
        request.put("conversationId", cascadeId)
        request.put("subscriberId", UUID.randomUUID().toString())
        request.put("trajectoryVerbosity", VERBOSITY_PROD_UI)
        request.put("disableRehydration", false)

        val thread = Thread({
            var failure: Throwable? = null
            try {
                connection.stream("StreamAgentStateUpdates", request) { envelope ->
                    val update = envelope.optJSONObject("update") ?: return@stream
                    onUpdate(update)
                }
            } catch (error: Throwable) {
                failure = error
            } finally {
                onDone(failure)
            }
        }, "hibou-agent-stream")
        thread.isDaemon = true
        thread.start()
        return HibouStreamHandle(thread, connection)
    }

    // -- history ---------------------------------------------------------

    fun conversations(): List<HibouConversationSummary> {
        val response = connect().unary("GetAllCascadeTrajectories", JSONObject())
        val summaries = response.optJSONObject("trajectorySummaries") ?: return emptyList()
        val keys = summaries.keys() ?: return emptyList()
        val result = mutableListOf<HibouConversationSummary>()
        while (keys.hasNext()) {
            val id = keys.next()
            val entry = summaries.optJSONObject(id) ?: continue
            result.add(HibouConversationSummary(
                id,
                titleOf(entry, id),
                entry.optInt("stepCount", 0),
                secondsToMillis(entry.optJSONObject("lastModifiedTime")),
                entry.optString("status", "") == "CASCADE_RUN_STATUS_RUNNING"
            ))
        }
        result.sortByDescending { it.updatedAt }
        return result
    }

    fun steps(cascadeId: String): List<HibouStep> {
        val request = JSONObject()
        request.put("cascadeId", cascadeId)
        request.put("trajectoryVerbosity", VERBOSITY_PROD_UI)
        val response = connect().unary("GetCascadeTrajectory", request)
        val trajectory = response.optJSONObject("trajectory") ?: return emptyList()
        return parseSteps(trajectory.optJSONArray("steps"))
    }

    fun models(): List<HibouModel> {
        val request = JSONObject()
        request.put("forceRefresh", false)
        val response = connect().unary("GetAvailableModels", request)
        val inner = response.optJSONObject("response") ?: return emptyList()
        val models = inner.optJSONObject("models") ?: return emptyList()
        val keys = models.keys() ?: return emptyList()
        val result = mutableListOf<HibouModel>()
        while (keys.hasNext()) {
            val id = keys.next()
            val details = models.optJSONObject(id) ?: continue
            if (details.optBoolean("disabled", false)) continue
            result.add(HibouModel(
                id,
                details.optString("displayName", id),
                details.optBoolean("recommended", false),
                details.optBoolean("supportsThinking", false)
            ))
        }
        result.sortWith(compareByDescending<HibouModel> { it.recommended }.thenBy { it.label })
        return result
    }

    // -- parsing ---------------------------------------------------------

    /** Flattens `mainTrajectoryUpdate.stepsUpdate.steps` into renderable steps. */
    fun stepsFromUpdate(update: JSONObject): List<HibouStep> {
        val main = update.optJSONObject("mainTrajectoryUpdate") ?: return emptyList()
        val stepsUpdate = main.optJSONObject("stepsUpdate") ?: return emptyList()
        val indices = stepsUpdate.optJSONArray("indices")
        return parseSteps(stepsUpdate.optJSONArray("steps"), indices)
    }

    fun parseSteps(steps: JSONArray?, indices: JSONArray? = null): List<HibouStep> {
        if (steps == null) return emptyList()
        val result = mutableListOf<HibouStep>()
        for (position in 0 until steps.length()) {
            val step = steps.optJSONObject(position) ?: continue
            val index = indices?.optInt(position, position) ?: position
            result.add(parseStep(index, step))
        }
        return result
    }

    private fun parseStep(index: Int, step: JSONObject): HibouStep {
        val type = step.optString("type", "CORTEX_STEP_TYPE_UNSPECIFIED")
        val status = step.optString("status", "CORTEX_STEP_STATUS_UNSPECIFIED")

        val planner = step.optJSONObject("plannerResponse")
        if (planner != null) {
            val text = planner.optString("modifiedResponse", "")
                .ifBlank { planner.optString("response", "") }
            return HibouStep(index, type, status, text, planner.optString("thinking", ""), null)
        }

        val userInput = step.optJSONObject("userInput")
        if (userInput != null) {
            val text = userInput.optString("query", "")
                .ifBlank { joinItems(userInput.optJSONArray("items")) }
            return HibouStep(index, type, status, text, "", null)
        }

        val tool = toolSummary(step)
        return HibouStep(index, type, status, "", "", tool)
    }

    private fun joinItems(items: JSONArray?): String {
        if (items == null) return ""
        val parts = mutableListOf<String>()
        for (position in 0 until items.length()) {
            val item = items.optJSONObject(position) ?: continue
            val text = item.optString("text", "")
            if (text.isNotBlank()) parts.add(text)
        }
        return parts.joinToString("\n")
    }

    private fun toolSummary(step: JSONObject): String? {
        val command = step.optJSONObject("runCommand")
        if (command != null) {
            return "Run: " + command.optString("commandLine", "").take(160)
        }
        val viewFile = step.optJSONObject("viewFile")
        if (viewFile != null) {
            return "Read: " + viewFile.optString("absolutePathUri", "").take(160)
        }
        val write = step.optJSONObject("writeToFile")
        if (write != null) {
            return "Write: " + write.optString("targetFileUri", "").take(160)
        }
        val grep = step.optJSONObject("grepSearch")
        if (grep != null) {
            return "Search: " + grep.optString("query", "").take(160)
        }
        val error = step.optJSONObject("errorMessage")?.optJSONObject("error")
        if (error != null) {
            val detail = error.optString("userErrorMessage", "")
                .ifBlank { error.optString("shortError", "") }
            if (detail.isNotBlank()) return detail.take(200)
        }
        return null
    }

    private fun titleOf(entry: JSONObject, id: String): String {
        val summary = entry.optString("summary", "")
        if (summary.isNotBlank()) return summary.take(80)
        val latest = entry.optJSONObject("latestNotifyUserStep")
        val step = latest?.optJSONObject("step")
        val notify = step?.optJSONObject("notifyUser")
        val content = notify?.optString("notificationContent", "") ?: ""
        if (content.isNotBlank()) return content.lineSequence().first().take(80)
        return "Conversation " + id.take(8)
    }

    private fun secondsToMillis(timestamp: JSONObject?): Long {
        if (timestamp == null) return 0L
        val seconds = timestamp.optLong("seconds", 0L)
        val nanos = timestamp.optLong("nanos", 0L)
        return seconds * 1000L + nanos / 1_000_000L
    }
}
